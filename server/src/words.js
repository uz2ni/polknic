// 걸리면 이유('word' / 'link'), 아니면 null
export function badText(s) {
  if (/(https?:|www\.|\.(com|net|kr|io|me|ly|gg)\b|open\.kakao|t\.me\/|discord\.gg)/i.test(s)) return 'link';
  const n = norm(s);
  return LIST.some(w => w && n.includes(w)) ? 'word' : null;
}
